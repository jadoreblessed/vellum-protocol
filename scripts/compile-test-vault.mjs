import { mkdir, readFile, writeFile } from "node:fs/promises";
import solc from "solc";

const testSourcePath = new URL("../contracts/VellumTestVault.sol", import.meta.url);
const vaultSourcePath = new URL("../contracts/VellumVault.sol", import.meta.url);
const [testSource, vaultSource] = await Promise.all([readFile(testSourcePath, "utf8"), readFile(vaultSourcePath, "utf8")]);
const input = {
  language: "Solidity",
  sources: {
    "VellumTestVault.sol": { content: testSource },
    "VellumVault.sol": { content: vaultSource },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = output.errors?.filter((item) => item.severity === "error") ?? [];
if (errors.length) throw new Error(errors.map((item) => item.formattedMessage).join("\n"));

const testVault = output.contracts["VellumTestVault.sol"].VellumTestVault;
const productionVault = output.contracts["VellumVault.sol"].VellumVault;
const testGenerated = `// Generated by scripts/compile-test-vault.mjs. Do not edit manually.\nexport const VELLUM_TEST_VAULT_ABI = ${JSON.stringify(testVault.abi)} as const;\n\nexport const VELLUM_TEST_VAULT_BYTECODE = "0x${testVault.evm.bytecode.object}" as const;\n`;
const productionGenerated = `// Generated by scripts/compile-test-vault.mjs. Do not edit manually.\nexport const VELLUM_VAULT_ABI = ${JSON.stringify(productionVault.abi)} as const;\n\nexport const VELLUM_VAULT_BYTECODE = "0x${productionVault.evm.bytecode.object}" as const;\n`;
await mkdir(new URL("../app/lib", import.meta.url), { recursive: true });
await Promise.all([
  writeFile(new URL("../app/lib/vellumTestVaultArtifact.ts", import.meta.url), testGenerated),
  writeFile(new URL("../app/lib/vellumVaultArtifact.ts", import.meta.url), productionGenerated),
]);
