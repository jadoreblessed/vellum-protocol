import { mkdir, readFile, writeFile } from "node:fs/promises";
import solc from "solc";

const sourcePath = new URL("../contracts/VellumTestVault.sol", import.meta.url);
const source = await readFile(sourcePath, "utf8");
const input = {
  language: "Solidity",
  sources: { "VellumTestVault.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = output.errors?.filter((item) => item.severity === "error") ?? [];
if (errors.length) throw new Error(errors.map((item) => item.formattedMessage).join("\n"));

const contract = output.contracts["VellumTestVault.sol"].VellumTestVault;
const generated = `// Generated by scripts/compile-test-vault.mjs. Do not edit manually.\nexport const VELLUM_TEST_VAULT_ABI = ${JSON.stringify(contract.abi)} as const;\n\nexport const VELLUM_TEST_VAULT_BYTECODE = "0x${contract.evm.bytecode.object}" as const;\n`;
await mkdir(new URL("../app/lib", import.meta.url), { recursive: true });
await writeFile(new URL("../app/lib/vellumTestVaultArtifact.ts", import.meta.url), generated);
